from pathlib import Path
from tempfile import TemporaryDirectory
import xml.etree.ElementTree as ET

import mujoco
import numpy as np

from mujoco_sim.configs import XgTsGaitConfig
from mujoco_sim.scripts.xg_ts import XgTsDeploy
from mujoco_sim.utils.gait_phase_generator import XgGaitPhaseGenerator


class XgTsGaitDeploy(XgTsDeploy):
    """Deploy the 55-D XG student using policy observations followed by gait phase."""

    def _init_control(self):
        super()._init_control()
        self._validate_student_policy_signature()
        self.gait = XgGaitPhaseGenerator(self.config)
        self._base_com_jacobian = np.zeros((3, self.robot.nv), dtype=np.float64)
        self._base_com_jacobian_dot = np.zeros_like(self._base_com_jacobian)

    def _validate_student_policy_signature(self):
        if self.config.num_obs != 55 or not self.config.is_rnn:
            raise ValueError("XgTsGaitDeploy requires num_obs=55 and is_rnn=True")
        signatures = (
            (
                "input", self.policy.get_inputs(),
                {"policy_obs": (1, 55), "h_in": (3, 1, 256), "c_in": (3, 1, 256)},
            ),
            (
                "output", self.policy.get_outputs(),
                {"actions": (1, 16), "h_out": (3, 1, 256), "c_out": (3, 1, 256)},
            ),
        )
        for kind, values, expected in signatures:
            if [value.name for value in values] != list(expected):
                raise ValueError(f"XG gait ONNX {kind} names must be {list(expected)}")
            for value in values:
                if tuple(value.shape) != expected[value.name] or value.type != "tensor(float)":
                    raise ValueError(
                        f"XG gait ONNX {kind} {value.name!r} must have shape "
                        f"{expected[value.name]} and type tensor(float), "
                        f"got {value.shape} and {value.type}"
                    )

    def _reset_control(self):
        super()._reset_control()
        self.gait.reset()
        self.obs[53:55] = self.gait.observation

    def _base_gait_state(self) -> tuple[float, np.ndarray]:
        """Return instantaneous COM ay and raw angular velocity in the base frame."""
        mujoco.mj_jacBodyCom(
            self.robot, self.data, self._base_com_jacobian, None, self._base_body_id
        )
        mujoco.mj_jacDot(
            self.robot, self.data, self._base_com_jacobian_dot, None,
            self.data.xipos[self._base_body_id], self._base_body_id,
        )
        acceleration_world = (
            self._base_com_jacobian @ self.data.qacc
            + self._base_com_jacobian_dot @ self.data.qvel
        )
        rotation_base_to_world = self.data.xmat[self._base_body_id].reshape(3, 3)
        acceleration_y = float((rotation_base_to_world.T @ acceleration_world)[1])
        angular_velocity = self.data.qvel[self._base_dof_adr + 3:self._base_dof_adr + 6]
        return acceleration_y, angular_velocity.copy()

    def step(self):
        # The first policy call reads reset phases. Later calls observe the phase
        # generated by the previous interval, before update_cmd changes its command.
        if self.counter > 0 and self.counter % self.control_decimation == 0:
            mujoco.mj_forward(self.robot, self.data)
            acceleration_y, angular_velocity = self._base_gait_state()
            self.gait.update(self.cmd, acceleration_y, angular_velocity)
        super().step()

    def update_obs(self):
        super().update_obs()
        self.obs[53:55] = self.gait.observation
        self.send_plotjuggler_data("gait_phase", self.obs[53:55])

    def _build_merged_xml(self, robot_xml_path, ball_xml_path, terrain_xml_path=None):
        # Resolve asset paths while copying XML into a temporary scene; the XG
        # model and its meshes live outside this writable workspace.
        self._scene_directory = TemporaryDirectory(prefix="xg_ts_gait_")
        merged = ET.Element("mujoco", model="xg_ts_gait")
        try:
            for path in (robot_xml_path, ball_xml_path, terrain_xml_path):
                if path is None:
                    continue
                path = Path(path).resolve()
                root = ET.parse(path).getroot()
                for asset in root.findall("./asset/*[@file]"):
                    asset.set("file", str((path.parent / asset.get("file")).resolve()))
                merged.extend(root)
            merged_path = Path(self._scene_directory.name) / "scene.xml"
            ET.ElementTree(merged).write(merged_path, encoding="utf-8")
            return str(merged_path)
        except BaseException:
            self._scene_directory.cleanup()
            raise

    def _load_model(self, merged_xml_path):
        try:
            return super()._load_model(merged_xml_path)
        finally:
            self._scene_directory.cleanup()


if __name__ == "__main__":
    deploy = XgTsGaitDeploy(XgTsGaitConfig())
    deploy.run()
